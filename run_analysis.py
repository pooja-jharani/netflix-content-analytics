"""Run the full analysis: cleaning, figures and a data-driven insights report.

Usage:
    python run_analysis.py
Outputs:
    reports/figures/*.png   charts used in the README
    reports/insights.md     findings, generated from the data
    reports/data_quality.csv
"""

from __future__ import annotations

from pathlib import Path

from netflix_analytics import analysis as A
from netflix_analytics import clean, data_quality_report, load_raw, quality_summary
from netflix_analytics.figures import make_all

ROOT = Path(__file__).parent
DATA = ROOT / "data" / "netflix_titles.csv"
REPORTS = ROOT / "reports"


def build_insights(df, quality) -> str:
    m = A.headline_metrics(df)
    countries = A.country_counts(df, 3)
    shift = A.non_us_shift_test(df)
    fresh = A.freshness_by_year(df)
    mix = A.rating_mix_by_year(df)
    runtime = A.runtime_by_release_year(df, start=2008)
    trend = A.runtime_trend_test(df)
    seasons = A.seasons_by_release_period(df)
    directors = A.director_concentration(df)
    monthly = A.monthly_additions(df)
    added = A.titles_added_per_year(df)
    totals = added.sum(axis=1)
    peak_year = int(totals.idxmax())
    sig = {c: A.signature_genre(df, c) for c in ("South Korea", "India", "United Kingdom", "Japan")}

    def sig_text(country):
        d = sig[country]
        return (f"{country}: **{d['genre']}** ({d['country_share']:.0%} of its titles vs "
                f"{d['overall_share']:.1%} overall, {d['lift']:.1f}x)")

    top3 = ", ".join(f"{c} ({n:,})" for c, n in countries.items())
    q4 = monthly.loc[[10, 11, 12]].mean()

    return f"""# Netflix Content Analytics - Findings

Generated by `run_analysis.py` from {m['titles']:,} titles. Every number below is computed from the data.

## Headline findings

1. **Netflix's catalogue became international fast.** The non-US share of titles added rose from
   {shift['early_share']:.0%} (2013-2015) to {shift['late_share']:.0%} (2017-2019), a statistically
   significant shift (chi-square p < 0.001). Top countries: {top3}.
2. **Additions peaked in {peak_year}** ({int(totals.max()):,} titles) and Q4 is the busiest season:
   about {q4:.0f} titles a month in Oct-Dec versus {monthly.loc[2]:.0f} in February.
3. **New arrivals are less often brand-new.** {fresh['new_share'].iloc[0]:.0%} of titles added in {fresh.index[0]}
   were released within a year; since 2018 that share is {fresh.loc[2018:, 'new_share'].mean():.0%}.
4. **Kids' content shrank, then recovered.** Its share of additions fell from {mix['Kids'].iloc[0]:.0%} in {mix.index[0]}
   to {mix['Kids'].min():.0%} (low point), and was {mix['Kids'].iloc[-1]:.0%} in {mix.index[-1]}. Adult-rated content
   (TV-MA, R, NC-17) is the largest group at {mix['Adult'].iloc[-1]:.0%} of {mix.index[-1]} additions.
5. **Countries specialise.** Strongest genre over-index (genres with 30+ titles): {sig_text('South Korea')};
   {sig_text('India')}; {sig_text('Japan')}; {sig_text('United Kingdom')}.
6. **Movies are getting shorter.** Median runtime fell from {runtime['median'].iloc[0]:.0f} minutes
   (release year {runtime.index[0]}) to {runtime['median'].iloc[-1]:.0f} ({runtime.index[-1]}). The Spearman correlation
   between release year and runtime is {trend['rho']:.2f} (p < 0.001, n = {trend['movies']:,}): significant but weak.
7. **Most TV shows have one season, in every era.** {seasons['one_season_share'].min():.0%} to
   {seasons['one_season_share'].max():.0%} of shows have a single season across all release periods, so this is not
   only a recency effect.
8. **Talent is highly fragmented.** {directors['unique_directors']:,} directors appear; {directors['directors_with_one_title_share']:.0%}
   have only one title and the top 10 account for just {directors['top_10_share_of_credits']:.1%} of credits.

## Data quality
- {quality['duplicates_removed']} exact duplicate row removed ({quality['rows_raw']:,} -> {quality['rows_clean']:,} titles).
- Missing: country {quality['missing_country']:,} ({quality['missing_country'] / quality['rows_raw']:.1%}),
  director {quality['missing_director']:,} ({quality['missing_director'] / quality['rows_raw']:.1%}),
  cast {quality['missing_cast']:,}, date added {quality['missing_date_added']}, rating {quality['missing_rating']}.
  Missing values are labelled "Unknown", never filled with the most common value.
- {quality['added_before_release']} titles have a date added earlier than their release year.

## Limitations
- The data is a snapshot that ends {df['date_added'].max():%d %B %Y}; the last year is incomplete and is excluded from trends.
- It lists titles available at the time, so older titles that were removed are missing (survivorship bias).
- There is no viewership data: "top" means "most titles", not "most watched". Findings describe
  what was in the catalogue, not what viewers chose.
- Only the first listed country is used, so co-productions count once. "International" tags describe
  geography, not genre, and are excluded from genre comparisons.

## Possible business questions this supports
- Which countries and genres are under-represented relative to their share elsewhere (candidates for regional investment)?
- Is the catalogue balanced across age groups, given the drop in kids' content after 2015?
- When should releases be scheduled, given the Q4 concentration of additions?
"""


def main() -> None:
    raw = load_raw(DATA)
    df = clean(raw)
    quality = quality_summary(raw, df)

    REPORTS.mkdir(exist_ok=True)
    data_quality_report(raw).to_csv(REPORTS / "data_quality.csv")
    paths = make_all(df, REPORTS / "figures")
    text = build_insights(df, quality)
    (REPORTS / "insights.md").write_text(text, encoding="utf-8")
    print(text)
    print(f"Saved {len(paths)} figures to {REPORTS / 'figures'}")


if __name__ == "__main__":
    main()
